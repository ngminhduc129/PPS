  function t(key, vars) {
    let value = (dict[lang] && dict[lang][key]) || (vi && vi[key]);
    if (value == null) {
      const parts = String(key).split('.');
      value = parts[parts.length - 1];
    }
    return String(value).replace(/\{(\w+)\}/g, function (m, name) {
      return vars && vars[name] != null ? String(vars[name]) : m;
    });
  }

  function apply(root) {
    root = root || document;
    if (!root.querySelectorAll) return;
    root.querySelectorAll('[data-i18n]').forEach(function (node) {
      node.textContent = t(node.getAttribute('data-i18n'));
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(function (node) {
      node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
    });
    root.querySelectorAll('[data-i18n-title]').forEach(function (node) {
      node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
    });
  }

